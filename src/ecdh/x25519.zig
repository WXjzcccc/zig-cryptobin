test "RFC 7748 X25519 Diffie-Hellman exchange" {
    const alice_secret_key = [_]u8{ 0x77, 0x07, 0x6d, 0x0a, 0x73, 0x18, 0xa5, 0x7d, 0x3c, 0x16, 0xc1, 0x72, 0x51, 0xb2, 0x66, 0x45, 0xdf, 0x4c, 0x2f, 0x87, 0xeb, 0xc0, 0x99, 0x2a, 0xb1, 0x77, 0xfb, 0xa5, 0x1d, 0xb9, 0x2c, 0x2a };
    const bob_secret_key = [_]u8{ 0x5d, 0xab, 0x08, 0x7e, 0x62, 0x4a, 0x8a, 0x4b, 0x79, 0xe1, 0x7f, 0x8b, 0x83, 0x80, 0x0e, 0xe6, 0x6f, 0x3b, 0xb1, 0x29, 0x26, 0x18, 0xb6, 0xfd, 0x1c, 0x2f, 0x8b, 0x27, 0xff, 0x88, 0xe0, 0xeb };
    const expected_secret = [_]u8{ 0x4a, 0x5d, 0x9d, 0x5b, 0xa4, 0xce, 0x2d, 0xe1, 0x72, 0x8e, 0x3b, 0xf4, 0x80, 0x35, 0x0f, 0x25, 0xe0, 0x7e, 0x21, 0xc9, 0x47, 0xd1, 0x9e, 0x33, 0x76, 0xf0, 0x9b, 0x3c, 0x1e, 0x16, 0x17, 0x42 };

    const alice = try KeyPair.fromSecretKey(alice_secret_key);
    const bob = try KeyPair.fromSecretKey(bob_secret_key);
    try std.testing.expectEqual(expected_secret, try ecdh(alice.secret_key, bob.public_key));
    try std.testing.expectEqual(expected_secret, try ecdh(bob.secret_key, alice.public_key));
}

test "X25519 rejects invalid key lengths" {
    try std.testing.expectError(error.InvalidSecretKeyLength, secretKeyFromBytes(&[_]u8{0} ** 31));
    try std.testing.expectError(error.InvalidPublicKeyLength, publicKeyFromBytes(&[_]u8{0} ** 31));
}
